# it writes no Thaumic Tinkerer code of its own, only wrappers that call the shared checks.
"""Keep the NeoForge GameTest catalogue of Thaumic Tinkerer in step with the Fabric one.

The Fabric wrappers (fabric/src/gameTest/java/thaumic/tinkerer/fabric/testing/*GameTests.java, the classes that
fabric/src/gameTest/resources/fabric.mod.json lists under "fabric-gametest") are the authored catalogue. The NeoForge
wrappers (neoforge/src/gameTest/java/thaumic/tinkerer/neoforge/testing/) are generated from them: the same classes, the
same tests in the same order under the same names, with the same attributes (timeouts, batches) and the template
"empty" of the namespace thaumictinkerer instead of Fabric's empty structure.

NeoForge names a test <class in lower case>.<method in lower case>, the name it has on Fabric, only when the class name
prefixes the template as well (@PrefixGameTestTemplate(true), NeoForge's default; with false the test is named after the
method alone, and the classes have tests of the same name). So the template of the wrappers of a class is
thaumictinkerer:<class in lower case>.empty, and each class has its empty structure:
neoforge/src/gameTest/resources/data/thaumictinkerer/structure/<class in lower case>.empty.nbt.

A Fabric wrapper whose body is one call of a shared check (thaumic.tinkerer.testing.*) gets the same body. Any other body
is Fabric-native (it uses the Fabric API or fixtures of its class); its NeoForge wrapper calls the method of the same name
of the hand-written class <Group>NeoForgeChecks (TileBlocksGameTests -> TileBlocksNeoForgeChecks), which must exist.

    --check  (default) the NeoForge files are exactly what --write would write, every Fabric-native wrapper has its
             NeoForge counterpart, no counterpart is left over, no NeoForge wrapper class lacks a Fabric one.
    --write  (re)write the generated files: one wrapper class per Fabric class, TinkererGameTestCatalogue.java (the
             classes the test mod registers, in the order of fabric.mod.json), the flat world preset (a byte copy of the
             Fabric one; it carries the Bedrock dimension the KamiWorld checks need) and the empty 8x8x8 structure of
             each class (the air of Fabric's fabric-gametest-api-v1:empty).

Deterministic and offline; it reads and writes only the files named above. Run from anywhere:
    python3 tools/neoforge_gametests.py [--check | --write]
common/src/test/java/thaumic/tinkerer/NeoForgeGameTestCatalogueTest.java checks the same agreement in the JUnit run.
"""
import argparse
import gzip
import json
from pathlib import Path
import re
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]
FABRIC_DIR = Path("fabric/src/gameTest/java/thaumic/tinkerer/fabric/testing")
FABRIC_MOD_JSON = Path("fabric/src/gameTest/resources/fabric.mod.json")
FABRIC_PACKAGE = "thaumic.tinkerer.fabric.testing"
NEOFORGE_DIR = Path("neoforge/src/gameTest/java/thaumic/tinkerer/neoforge/testing")
NEOFORGE_PACKAGE = "thaumic.tinkerer.neoforge.testing"
CATALOGUE = "TinkererGameTestCatalogue"
PRESET = Path("data/minecraft/worldgen/world_preset/flat.json")
FABRIC_PRESET = Path("fabric/src/gameTest/resources") / PRESET
NEOFORGE_PRESET = Path("neoforge/src/gameTest/resources") / PRESET
STRUCTURE_DIR = Path("neoforge/src/gameTest/resources/data/thaumictinkerer/structure")
SHARED_CHECKS = "thaumic.tinkerer.testing."
FABRIC_TEMPLATE = "template = FabricGameTest.EMPTY_STRUCTURE"
NEOFORGE_TEMPLATE = 'template = "empty", templateNamespace = "thaumictinkerer"'
# The data version of Minecraft 1.21.1 (SharedConstants.WORLD_VERSION), written into the empty structure.
DATA_VERSION = 3955

HEADER = """/**
 * New in the 1.21.1 port of Thaumic Tinkerer (no 1.7.10 counterpart): the NeoForge GameTest harness, test-only. Distributed under the
 * same licence as the add-on (CC BY-NC-SA 3.0, see NOTICE.md).
 *
 * Generated by tools/neoforge_gametests.py (--write) from
 * %s; do not edit by hand.
 */
"""

_SIGNATURE = re.compile(r"\s*public\s+void\s+(\w+)\s*\(\s*GameTestHelper\s+(\w+)\s*\)\s*")
_DELEGATION = re.compile(r"\{\s*(\w+)\.(\w+)\(\s*(\w+)\s*\)\s*;\s*\}")


def _skip_literal(src, j):
    """Index after the string or char literal that starts at ``j``."""
    quote = src[j]
    if src.startswith('"""', j):
        end = src.index('"""', j + 3)
        return end + 3
    j += 1
    while src[j] != quote:
        j += 2 if src[j] == "\\" else 1
    return j + 1


def _skip_comment(src, j):
    """Index after the comment that starts at ``j``, or ``j`` if none starts there."""
    if src.startswith("//", j):
        end = src.find("\n", j)
        return len(src) if end < 0 else end
    if src.startswith("/*", j):
        return src.index("*/", j + 2) + 2
    return j


def _match(src, start, open_c, close_c):
    """Index of the bracket that closes the one at ``start``; literals and comments are skipped."""
    depth = 0
    j = start
    while j < len(src):
        ch = src[j]
        if ch in "\"'":
            j = _skip_literal(src, j)
            continue
        after = _skip_comment(src, j)
        if after != j:
            j = after
            continue
        if ch == open_c:
            depth += 1
        elif ch == close_c:
            depth -= 1
            if depth == 0:
                return j
        j += 1
    raise ValueError("unbalanced %s%s from offset %d" % (open_c, close_c, start))


def wrappers(src, where):
    """Every @GameTest method of a wrapper class: its annotation, name, parameter, body and the Javadoc right before it."""
    out = []
    for found in re.finditer(r"@GameTest\(", src):
        a0 = found.start()
        a1 = _match(src, found.end() - 1, "(", ")") + 1
        sig = _SIGNATURE.match(src, a1)
        if not sig:
            raise ValueError("%s: no `public void name(GameTestHelper x)` after %s" % (where, src[a0:a1]))
        b0 = sig.end()
        if src[b0] != "{":
            raise ValueError("%s: the wrapper %s has no body" % (where, sig.group(1)))
        b1 = _match(src, b0, "{", "}") + 1
        line_start = src.rfind("\n", 0, a0) + 1
        doc = None
        before = src[:line_start].rstrip()
        if before.endswith("*/"):
            d0 = before.rfind("/**")
            if d0 >= 0 and before.find("*/", d0) == len(before) - 2:
                doc = before[before.rfind("\n", 0, d0) + 1:]
        out.append(dict(attributes=src[found.end():a1 - 1], name=sig.group(1), param=sig.group(2),
                        body=src[b0:b1], doc=doc))
    return out


def imports(src):
    return re.findall(r"^import\s+([\w.]+)\s*;", src, re.M)


def shared_delegate(method, src):
    """The simple name of the shared checks class the body calls, or None if the body is Fabric-native."""
    found = _DELEGATION.fullmatch(method["body"])
    if not found or found.group(3) != method["param"]:
        return None
    owner = found.group(1)
    if any(name == SHARED_CHECKS + owner for name in imports(src)):
        return owner
    return None


def fabric_classes(root):
    """The Fabric wrapper classes in the order of fabric.mod.json (the order the Fabric run registers them in)."""
    meta = json.loads((root / FABRIC_MOD_JSON).read_text(encoding="utf-8"))
    names = []
    for entry in meta["entrypoints"]["fabric-gametest"]:
        entry = entry if isinstance(entry, str) else entry["value"]
        if not entry.startswith(FABRIC_PACKAGE + "."):
            raise ValueError("%s: the entrypoint %s is outside %s" % (FABRIC_MOD_JSON, entry, FABRIC_PACKAGE))
        names.append(entry[len(FABRIC_PACKAGE) + 1:])
    on_disk = sorted(p.stem for p in (root / FABRIC_DIR).glob("*GameTests.java"))
    missing = sorted(set(on_disk) - set(names))
    if missing:
        raise ValueError("%s does not list the Fabric wrapper classes %s" % (FABRIC_MOD_JSON, missing))
    return names


def structure_of(fabric_class):
    return STRUCTURE_DIR / (fabric_class.lower() + ".empty.nbt")


def stray_files(root, files):
    """Files of the generated kinds that --write would not write: wrapper classes and structures without a Fabric class."""
    stray = [NEOFORGE_DIR / p.name for p in sorted((root / NEOFORGE_DIR).glob("*GameTests.java"))]
    if (root / STRUCTURE_DIR).is_dir():
        stray += [STRUCTURE_DIR / p.name for p in sorted((root / STRUCTURE_DIR).glob("*.nbt"))]
    return [rel for rel in stray if rel not in files]


def counterpart_class(fabric_class):
    return fabric_class[:-len("GameTests")] + "NeoForgeChecks"


def counterpart_methods(src):
    return re.findall(r"public\s+static\s+void\s+(\w+)\s*\(\s*GameTestHelper\s+\w+\s*\)", src)


def generate_wrapper(name, src):
    """The NeoForge wrapper class for the Fabric class ``name`` and the names of its Fabric-native wrappers."""
    where = str(FABRIC_DIR / (name + ".java"))
    methods = wrappers(src, where)
    if not methods:
        raise ValueError("%s has no @GameTest wrapper" % where)
    needed = {"net.minecraft.gametest.framework.GameTest", "net.minecraft.gametest.framework.GameTestHelper",
              "net.neoforged.neoforge.gametest.PrefixGameTestTemplate"}
    native = []
    parts = []
    for method in methods:
        attributes = method["attributes"]
        if FABRIC_TEMPLATE not in attributes:
            raise ValueError("%s: %s does not use %s" % (where, method["name"], FABRIC_TEMPLATE))
        attributes = attributes.replace(FABRIC_TEMPLATE, NEOFORGE_TEMPLATE)
        if "Fabric" in attributes:
            raise ValueError("%s: an untranslated Fabric attribute on %s: %s" % (where, method["name"], attributes))
        owner = shared_delegate(method, src)
        text = ""
        if owner is not None:
            needed.add(SHARED_CHECKS + owner)
            if method["doc"]:
                text += method["doc"] + "\n"
            body = method["body"]
        else:
            native.append(method["name"])
            target = counterpart_class(name)
            text += ("    /** Fabric-native on Fabric (its body uses the Fabric API): the NeoForge counterpart is {@link %s#%s}. */\n"
                     % (target, method["name"]))
            body = "{\n        %s.%s(%s);\n    }" % (target, method["name"], method["param"])
        text += "    @GameTest(%s)\n" % attributes
        text += "    public void %s(GameTestHelper %s) %s\n" % (method["name"], method["param"], body)
        parts.append(text)
    shared = sorted(n[len(SHARED_CHECKS):] for n in needed if n.startswith(SHARED_CHECKS))
    if len(shared) == 1:
        about = "NeoForge wrappers of {@link %s}" % shared[0]
    elif shared:
        about = "NeoForge wrappers of the checks of " + ", ".join("{@link %s}" % s for s in shared)
    else:
        about = "NeoForge wrappers"
    out = HEADER % (FABRIC_DIR / (name + ".java")).as_posix()
    out += "package %s;\n\n" % NEOFORGE_PACKAGE
    out += "".join("import %s;\n" % n for n in sorted(needed))
    out += "\n/**\n"
    out += (" * %s, generated from the Fabric class\n"
            " * {@code %s.%s}: the same tests in the same order, under the same names and with\n"
            " * the same timeouts and batches, on the template {@code thaumictinkerer:%s.empty} (the class name prefixes the\n"
            " * template and the test names, which are then those of the Fabric run). Test-only, not distributed.\n"
            % (about, FABRIC_PACKAGE, name, name.lower()))
    if native:
        out += (" * The Fabric-native wrappers (%s) call their NeoForge counterparts in {@link %s}.\n"
                % (", ".join(native), counterpart_class(name)))
    out += " */\n"
    out += "@PrefixGameTestTemplate(true)\n"
    out += "public final class %s {\n" % name
    out += "\n".join(parts)
    out += "}\n"
    return out, [m["name"] for m in methods], native


def generate_catalogue(names):
    out = HEADER % FABRIC_MOD_JSON.as_posix()
    out += "package %s;\n\n" % NEOFORGE_PACKAGE
    out += "import java.util.List;\n\n"
    out += ("/** The wrapper classes that {@link ThaumicTinkererGameTestMod} registers: those of the Fabric harness, in its order. */\n"
            "public final class %s {\n"
            "    public static final List<Class<?>> CLASSES = List.of(\n" % CATALOGUE)
    out += ",\n".join("            %s.class" % n for n in names)
    out += ");\n\n"
    out += "    private %s() {}\n}\n" % CATALOGUE
    return out


def _nbt_string(text):
    data = text.encode("utf-8")
    return struct.pack(">H", len(data)) + data


def _named(tag, name):
    return struct.pack(">b", tag) + _nbt_string(name)


def empty_structure():
    """The gzipped NBT of an empty 8x8x8 structure of air, like Fabric's fabric-gametest-api-v1:empty (empty.snbt)."""
    TAG_END, TAG_INT, TAG_STRING, TAG_LIST, TAG_COMPOUND = 0, 3, 8, 9, 10
    body = _named(TAG_INT, "DataVersion") + struct.pack(">i", DATA_VERSION)
    body += _named(TAG_LIST, "size") + struct.pack(">bi", TAG_INT, 3) + struct.pack(">iii", 8, 8, 8)
    blocks = b""
    for y in range(8):
        for x in range(8):
            for z in range(8):
                blocks += _named(TAG_LIST, "pos") + struct.pack(">bi", TAG_INT, 3) + struct.pack(">iii", x, y, z)
                blocks += _named(TAG_INT, "state") + struct.pack(">i", 0)
                blocks += struct.pack(">b", TAG_END)
    body += _named(TAG_LIST, "blocks") + struct.pack(">bi", TAG_COMPOUND, 512) + blocks
    body += _named(TAG_LIST, "entities") + struct.pack(">bi", TAG_END, 0)
    palette = _named(TAG_STRING, "Name") + _nbt_string("minecraft:air") + struct.pack(">b", TAG_END)
    body += _named(TAG_LIST, "palette") + struct.pack(">bi", TAG_COMPOUND, 1) + palette
    root = _named(TAG_COMPOUND, "") + body + struct.pack(">b", TAG_END)
    return gzip.compress(root, compresslevel=9, mtime=0)


def expected_files(root):
    """Every generated file (relative path -> bytes) and the problems that generation alone finds."""
    files = {}
    problems = []
    names = fabric_classes(root)
    native_by_class = {}
    for name in names:
        src = (root / FABRIC_DIR / (name + ".java")).read_text(encoding="utf-8")
        text, _, native = generate_wrapper(name, src)
        files[NEOFORGE_DIR / (name + ".java")] = text.encode("utf-8")
        native_by_class[name] = native
    files[NEOFORGE_DIR / (CATALOGUE + ".java")] = generate_catalogue(names).encode("utf-8")
    files[NEOFORGE_PRESET] = (root / FABRIC_PRESET).read_bytes()
    for name in names:
        files[structure_of(name)] = empty_structure()
    # The hand-written counterparts of the Fabric-native wrappers.
    for name, native in native_by_class.items():
        path = root / NEOFORGE_DIR / (counterpart_class(name) + ".java")
        have = counterpart_methods(path.read_text(encoding="utf-8")) if path.is_file() else []
        for method in native:
            if method not in have:
                problems.append("%s.%s is Fabric-native (its body is not one call of a shared check): add `public static void %s"
                                "(GameTestHelper h)` to %s, or move the body into the shared checks of common/src/gameTest"
                                % (name, method, method, (NEOFORGE_DIR / path.name).as_posix()))
        for method in have:
            if method not in native:
                problems.append("%s has %s, which no Fabric-native wrapper of %s needs"
                                % ((NEOFORGE_DIR / path.name).as_posix(), method, name))
    for path in sorted((root / NEOFORGE_DIR).glob("*NeoForgeChecks.java")):
        group = path.stem[:-len("NeoForgeChecks")] + "GameTests"
        if group not in native_by_class:
            problems.append("%s has no Fabric wrapper class %s" % ((NEOFORGE_DIR / path.name).as_posix(), group))
    return files, problems, names


def check(root):
    files, problems, names = expected_files(root)
    for rel, data in files.items():
        path = root / rel
        if not path.is_file():
            problems.append("%s is missing (run python3 tools/neoforge_gametests.py --write)" % rel.as_posix())
        elif path.read_bytes() != data:
            problems.append("%s differs from what the Fabric wrappers generate (run python3 tools/neoforge_gametests.py --write)"
                            % rel.as_posix())
    for rel in stray_files(root, files):
        problems.append("%s was not generated from a Fabric wrapper class (run python3 tools/neoforge_gametests.py --write)"
                        % rel.as_posix())
    return problems, names


def write(root):
    files, problems, names = expected_files(root)
    for rel, data in files.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.is_file() or path.read_bytes() != data:
            path.write_bytes(data)
            print("wrote", rel.as_posix())
    for rel in stray_files(root, files):
        (root / rel).unlink()
        print("removed", rel.as_posix())
    return problems, names


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="compare the NeoForge files with the Fabric wrappers (default)")
    mode.add_argument("--write", action="store_true", help="regenerate the NeoForge files")
    parser.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    try:
        problems, names = (write if args.write else check)(args.root)
        if args.write:
            problems = check(args.root)[0]
    except (OSError, ValueError, KeyError) as error:
        print("neoforge_gametests: %s" % error, file=sys.stderr)
        return 2
    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        return 1
    total = sum(len(wrappers((args.root / FABRIC_DIR / (n + ".java")).read_text(encoding="utf-8"), n)) for n in names)
    print("The NeoForge GameTest catalogue matches the Fabric one (%d classes, %d wrappers)" % (len(names), total))
    return 0


if __name__ == "__main__":
    sys.exit(main())
