import java.util.stream.Stream;
import org.junit.jupiter.api.Test;

/**
 * The NeoForge GameTest catalogue (neoforge/src/gameTest/.../testing, generated by tools/neoforge_gametests.py) agrees with the Fabric
 * one (fabric/src/gameTest/.../testing, the authored wrappers): every Fabric wrapper class has a NeoForge class of the same name that the
 * test mod registers in the same order, with the same tests in the same order, the same attributes (the template translated) and the same
 * body (one call of a shared check), and with its template {@code thaumictinkerer:<class>.empty}. A Fabric wrapper with any other body is Fabric-native; its NeoForge wrapper calls the method of the same
 * name of {@code <Group>NeoForgeChecks}, which must exist. The hand-written NeoForge-only classes ({@code *NeoForgeTests}) are registered as
 * well and have the template of the wrappers. It reads the sources itself (no Python needed); the generator's {@code --check}
 * compares the files byte for byte as well.
 */
class NeoForgeGameTestCatalogueTest {
    private static final Path FABRIC_DIR = Path.of("fabric", "src", "gameTest", "java", "thaumic", "tinkerer", "fabric", "testing");
    private static final Path FABRIC_MOD_JSON = Path.of("fabric", "src", "gameTest", "resources", "fabric.mod.json");
    private static final Path NEOFORGE_DIR = Path.of("neoforge", "src", "gameTest", "java", "thaumic", "tinkerer", "neoforge", "testing");
    private static final Path STRUCTURES = Path.of("neoforge", "src", "gameTest", "resources", "data", "thaumictinkerer", "structure");
    private static final Path PRESET = Path.of("data", "minecraft", "worldgen", "world_preset", "flat.json");
    private static final String FABRIC_PACKAGE = "thaumic.tinkerer.fabric.testing.";
    private static final String FABRIC_TEMPLATE = "template = FabricGameTest.EMPTY_STRUCTURE";
    private static final String NEOFORGE_TEMPLATE = "template = \"empty\", templateNamespace = \"thaumictinkerer\"";
    private static final Pattern SIGNATURE = Pattern.compile("\\s*public\\s+void\\s+(\\w+)\\s*\\(\\s*GameTestHelper\\s+(\\w+)\\s*\\)\\s*");
    private static final Pattern DELEGATION = Pattern.compile("\\{\\s*(\\w+)\\.(\\w+)\\(\\s*(\\w+)\\s*\\)\\s*;\\s*}");

    /** One {@code @GameTest} method: the attributes of the annotation, the name, the parameter, the body. */
    private record Wrapper(String attributes, String name, String param, String body) {}

    @Test
    void everyFabricWrapperHasTheSameNeoForgeWrapper() throws IOException {
        List<String> problems = new ArrayList<>();
        int total = 0;
        for (String name : fabricClasses()) {
            String fabricSrc = read(FABRIC_DIR.resolve(name + ".java"));
            Path neoPath = NEOFORGE_DIR.resolve(name + ".java");
            if (!Files.isRegularFile(neoPath)) {
                problems.add(name + ": no NeoForge wrapper class " + neoPath);
                continue;
            }
            String neoSrc = read(neoPath);
            List<Wrapper> fabric = wrappers(fabricSrc, name);
            Map<String, Wrapper> neo = new LinkedHashMap<>();
            for (Wrapper w : wrappers(neoSrc, neoPath.toString())) neo.put(w.name(), w);
            total += fabric.size();
            // NeoForge names a test <class>.<method> (the Fabric name) only when the class name prefixes the template too.
            if (!neoSrc.contains("@PrefixGameTestTemplate(true)")) problems.add(name + ": the NeoForge class is not @PrefixGameTestTemplate(true)");
            Path structure = STRUCTURES.resolve(name.toLowerCase(Locale.ROOT) + ".empty.nbt");
            if (!Files.isRegularFile(structure)) problems.add(name + ": no template " + structure);
            List<String> order = fabric.stream().map(Wrapper::name).toList();
            if (!order.equals(List.copyOf(neo.keySet()))) {
                problems.add(name + ": the NeoForge tests " + neo.keySet() + " are not the Fabric tests " + order);
            }
            String counterparts = name.substring(0, name.length() - "GameTests".length()) + "NeoForgeChecks";
            for (Wrapper f : fabric) {
                Wrapper n = neo.get(f.name());
                if (n == null) continue;
                String attributes = f.attributes().replace(FABRIC_TEMPLATE, NEOFORGE_TEMPLATE);
                if (!norm(attributes).equals(norm(n.attributes()))) {
                    problems.add(name + "." + f.name() + ": @GameTest(" + n.attributes() + ") on NeoForge, @GameTest(" + f.attributes() + ") on Fabric");
                }
                String expected;
                if (delegatesToASharedCheck(f, fabricSrc)) {
                    expected = f.body().replaceAll("\\b" + Pattern.quote(f.param()) + "\\b", n.param());
                } else {
                    expected = "{ " + counterparts + "." + f.name() + "(" + n.param() + "); }";
                    Path counterpartFile = NEOFORGE_DIR.resolve(counterparts + ".java");
                    boolean present = Files.isRegularFile(counterpartFile) && Pattern.compile("public\\s+static\\s+void\\s+"
                            + Pattern.quote(f.name()) + "\\s*\\(\\s*GameTestHelper\\s+\\w+\\s*\\)").matcher(read(counterpartFile)).find();
                    if (!present) problems.add(name + "." + f.name() + " is Fabric-native and " + counterpartFile + " has no " + f.name() + "(GameTestHelper)");
                }
                if (!norm(expected).equals(norm(n.body()))) {
                    problems.add(name + "." + f.name() + ": the NeoForge body " + norm(n.body()) + " is not " + norm(expected));
                }
            }
        }
        assertEquals(List.of(), problems, "the NeoForge GameTests drifted from the Fabric ones; run python3 tools/neoforge_gametests.py --write");
        assertTrue(total >= 300, "the Fabric catalogue was read: " + total + " wrappers");
    }

    @Test
    void theTestModRegistersTheFabricClassesInTheirOrderAndTheNeoForgeOnlyOnes() throws IOException {
        String catalogue = read(NEOFORGE_DIR.resolve("TinkererGameTestCatalogue.java"));
        assertEquals(fabricClasses(), listed(catalogue, "CLASSES"), "TinkererGameTestCatalogue.CLASSES lists the classes of fabric.mod.json in their order");
        assertEquals(neoForgeOnlyClasses(), listed(catalogue, "NEOFORGE_ONLY"), "TinkererGameTestCatalogue.NEOFORGE_ONLY lists the *NeoForgeTests classes");
        String mod = read(NEOFORGE_DIR.resolve("ThaumicTinkererGameTestMod.java"));
        assertTrue(mod.contains("TinkererGameTestCatalogue.CLASSES") && mod.contains("TinkererGameTestCatalogue.NEOFORGE_ONLY"),
                "the test mod registers both lists of the catalogue");
    }

    /** The hand-written NeoForge-only scenarios have the template and the test names of the wrappers. */
    @Test
    void theNeoForgeOnlyClassesUseTheTemplateOfTheWrappers() throws IOException {
        List<String> problems = new ArrayList<>();
        for (String name : neoForgeOnlyClasses()) {
            String src = read(NEOFORGE_DIR.resolve(name + ".java"));
            List<Wrapper> tests = wrappers(src, name);
            if (tests.isEmpty()) problems.add(name + " has no @GameTest method");
            if (!src.contains("@PrefixGameTestTemplate(true)")) problems.add(name + " is not @PrefixGameTestTemplate(true)");
            for (Wrapper w : tests) if (!norm(w.attributes()).contains(norm(NEOFORGE_TEMPLATE))) problems.add(name + "." + w.name() + " has another template");
            if (!Files.isRegularFile(STRUCTURES.resolve(name.toLowerCase(Locale.ROOT) + ".empty.nbt"))) problems.add(name + " has no template structure");
        }
        assertEquals(List.of(), problems, "the NeoForge-only GameTest classes");
    }

    @Test
    void everyNeoForgeWrapperClassHasAFabricOne() throws IOException {
        List<String> fabric = fabricClasses();
        List<String> stray = new ArrayList<>();
        try (Stream<Path> files = Files.list(NEOFORGE_DIR)) {
            for (Path file : files.toList()) {
                String stem = file.getFileName().toString().replaceFirst("\\.java$", "");
                if (stem.endsWith("GameTests") && !fabric.contains(stem)) stray.add(stem);
                if (stem.endsWith("NeoForgeChecks") && !fabric.contains(stem.replaceFirst("NeoForgeChecks$", "GameTests"))) stray.add(stem);
            }
        }
        assertEquals(List.of(), stray, "NeoForge GameTest classes without a Fabric wrapper class");
    }

    @Test
    void theFlatWorldPresetIsTheFabricOne() throws IOException {
        // It carries the Bedrock dimension that the KamiWorld checks need; the GameTest server makes its world from it.
        assertArrayEquals(Files.readAllBytes(Path.of("fabric", "src", "gameTest", "resources").resolve(PRESET)),
                Files.readAllBytes(Path.of("neoforge", "src", "gameTest", "resources").resolve(PRESET)),
                "neoforge/src/gameTest/resources/" + PRESET + " is a copy of the Fabric one");
    }

    private static List<String> fabricClasses() throws IOException {
        List<String> names = new ArrayList<>();
        for (JsonElement entry : JsonParser.parseString(read(FABRIC_MOD_JSON)).getAsJsonObject()
                .getAsJsonObject("entrypoints").getAsJsonArray("fabric-gametest")) {
            String value = entry.isJsonObject() ? entry.getAsJsonObject().get("value").getAsString() : entry.getAsString();
            assertTrue(value.startsWith(FABRIC_PACKAGE), "a Fabric wrapper class: " + value);
            names.add(value.substring(FABRIC_PACKAGE.length()));
        }
        assertTrue(!names.isEmpty(), "fabric.mod.json lists the Fabric wrappers: " + Path.of(".").toAbsolutePath());
        return names;
    }

    private static List<String> listed(String catalogue, String field) {
        Matcher block = Pattern.compile("List<Class<\\?>>\\s+" + field + "\\s*=\\s*List\\.of\\(([^)]*)\\)").matcher(catalogue);
        assertTrue(block.find(), "TinkererGameTestCatalogue has the list " + field);
        List<String> names = new ArrayList<>();
        Matcher m = Pattern.compile("(\\w+)\\.class").matcher(block.group(1));
        while (m.find()) names.add(m.group(1));
        return names;
    }

    private static List<String> neoForgeOnlyClasses() throws IOException {
        try (Stream<Path> files = Files.list(NEOFORGE_DIR)) {
            return files.map(f -> f.getFileName().toString()).filter(n -> n.endsWith("NeoForgeTests.java"))
                    .map(n -> n.substring(0, n.length() - ".java".length())).sorted().toList();
        }
    }

    private static boolean delegatesToASharedCheck(Wrapper w, String src) {
        Matcher m = DELEGATION.matcher(w.body());
        return m.matches() && m.group(3).equals(w.param())
                && Pattern.compile("^import\\s+thaumic\\.tinkerer\\.testing\\." + Pattern.quote(m.group(1)) + "\\s*;", Pattern.MULTILINE).matcher(src).find();
    }

    private static List<Wrapper> wrappers(String src, String where) {
        List<Wrapper> out = new ArrayList<>();
        int from = 0;
        while (true) {
            int a0 = src.indexOf("@GameTest(", from);
            if (a0 < 0) return out;
            int open = a0 + "@GameTest".length();
            int close = match(src, open, '(', ')');
            Matcher sig = SIGNATURE.matcher(src);
            sig.region(close + 1, src.length());
            assertTrue(sig.lookingAt(), where + ": no `public void name(GameTestHelper x)` after " + src.substring(a0, close + 1));
            int b0 = sig.end();
            assertEquals('{', src.charAt(b0), where + ": " + sig.group(1) + " has a body");
            int b1 = match(src, b0, '{', '}');
            out.add(new Wrapper(src.substring(open + 1, close), sig.group(1), sig.group(2), src.substring(b0, b1 + 1)));
            from = b1 + 1;
        }
    }

    /** The index of the bracket that closes the one at {@code start}; string and char literals and comments are skipped. */
    private static int match(String src, int start, char open, char close) {
        int depth = 0;
        for (int j = start; j < src.length(); j++) {
            char ch = src.charAt(j);
            if (ch == '"' || ch == '\'') {
                for (j++; src.charAt(j) != ch; j++) if (src.charAt(j) == '\\') j++;
            } else if (src.startsWith("//", j)) {
                j = src.indexOf('\n', j);
                if (j < 0) break;
            } else if (src.startsWith("/*", j)) {
                j = src.indexOf("*/", j + 2) + 1;
            } else if (ch == open) {
                depth++;
            } else if (ch == close && --depth == 0) {
                return j;
            }
        }
        throw new AssertionError("unbalanced " + open + close + " from offset " + start);
    }

    private static String norm(String text) {
        return text.replaceAll("\\s+", " ").replaceAll("\\s*([(){};,])\\s*", "$1").trim();
    }

    private static String read(Path path) throws IOException {
        return Files.readString(path, StandardCharsets.UTF_8);
    }
}
